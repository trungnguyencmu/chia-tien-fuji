export type IconName = keyof typeof ICONS;

interface IconProps {
  name: IconName;
  size?: number;
  className?: string;
  /** Set only when the icon carries meaning on its own; otherwise it is hidden from assistive tech. */
  label?: string;
}

export function Icon({ name, size = 18, className = '', label }: IconProps) {
  return (
    <svg
      className={`icon ${className}`.trim()}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      role={label ? 'img' : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
      focusable="false"
    >
      {ICONS[name]}
    </svg>
  );
}

/** Spinning loader used inside buttons and inline loading states. */
export function Spinner({ size = 18 }: { size?: number }) {
  return <Icon name="loader" size={size} className="icon-spin" />;
}
